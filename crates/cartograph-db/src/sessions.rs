/// One validated saved macro step.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct McpMacroStep {
    tool: String,
    #[serde(default)]
    args: Map<String, Value>,
}

impl McpMacroStep {
    /// Creates a validated MCP macro step.
    ///
    /// # Errors
    ///
    /// Returns an error if the tool name is invalid or the argument object is
    /// not serializable within the trace payload byte bound.
    pub fn new(tool: &str, args: Map<String, Value>) -> Result<Self, StorageError> {
        validate_tool_name(tool)?;
        validate_arguments(&Value::Object(args.clone()))?;
        Ok(Self {
            tool: tool.to_owned(),
            args,
        })
    }

    #[must_use]
    /// Returns the tool.
    pub fn tool(&self) -> &str {
        &self.tool
    }

    #[must_use]
    /// Returns the args.
    pub const fn args(&self) -> &Map<String, Value> {
        &self.args
    }
}

/// Validated macro upsert.
pub struct NewMcpMacro {
    name: String,
    steps: Vec<McpMacroStep>,
}

impl NewMcpMacro {
    /// Creates a validated new MCP macro.
    ///
    /// # Errors
    ///
    /// Returns an error if the macro name or step count is invalid, or any
    /// validated step would exceed the aggregate recipe bound.
    pub fn new(name: &str, steps: Vec<McpMacroStep>) -> Result<Self, StorageError> {
        validate_macro_name(name)?;
        validate_macro_steps(&steps)?;
        Ok(Self {
            name: name.to_owned(),
            steps,
        })
    }
}

