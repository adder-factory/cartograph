//! Exact builtin vocabularies share one membership lookup without widening resolution.

pub(super) enum BuiltinVocabulary {
    PythonExceptions,
    PythonValues,
    JavascriptMembers,
}

impl BuiltinVocabulary {
    pub(super) fn contains(self, name: &str) -> bool {
        let names = match self {
            Self::PythonExceptions => PYTHON_EXCEPTIONS,
            Self::PythonValues => PYTHON_VALUES,
            Self::JavascriptMembers => JAVASCRIPT_MEMBERS,
        };
        names.contains(&name)
    }
}

