/// Validated tool-call trace payload. Arguments must already be privacy-redacted.
pub struct McpToolCallInput {
    tool_name: String,
    arguments: Value,
    result_summary: String,
    success: bool,
    duration_ms: u64,
}

/// Privacy-redacted values for one validated tool-call trace.
pub struct McpToolCallData<'input> {
    /// Tool name for this record.
    pub tool_name: &'input str,
    /// Arguments for this record.
    pub arguments: Value,
    /// Result summary for this record.
    pub result_summary: &'input str,
    /// Whether this value is success.
    pub success: bool,
    /// Duration duration in milliseconds.
    pub duration_ms: u64,
}

impl McpToolCallInput {
    /// Creates a validated MCP tool call input.
    ///
    /// # Errors
    ///
    /// Returns an error if tool name/result text bounds fail or privacy-redacted
    /// arguments are not a bounded serializable JSON object.
    pub fn new(input: McpToolCallData<'_>) -> Result<Self, StorageError> {
        validate_tool_name(input.tool_name)?;
        validate_arguments(&input.arguments)?;
        validate_result_summary(input.result_summary)?;
        Ok(Self {
            tool_name: input.tool_name.to_owned(),
            arguments: input.arguments,
            result_summary: input.result_summary.to_owned(),
            success: input.success,
            duration_ms: input.duration_ms,
        })
    }
}

