/// Durable session origin.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum McpSessionKind {
    /// Session identity generated by Cartograph.
    Automatic,
    /// Caller-supplied, validated session identity.
    Named,
}

impl McpSessionKind {}

/// Validated new durable trace session.
pub struct NewMcpSession {
    kind: McpSessionKind,
    label: Option<String>,
    objective: String,
}

impl NewMcpSession {
    #[must_use]
    /// Returns the automatic.
    pub fn automatic() -> Self {
        Self {
            kind: McpSessionKind::Automatic,
            label: None,
            objective: String::new(),
        }
    }

    /// Returns the named.
    ///
    /// # Errors
    ///
    /// Returns an error if `label` or `objective` is empty where required,
    /// oversized, or contains a NUL byte.
    pub fn named(label: &str, objective: &str) -> Result<Self, StorageError> {
        Self::named_optional(Some(label), objective)
    }

    /// Returns the named optional.
    ///
    /// # Errors
    ///
    /// Returns an error if the optional label or required objective violates
    /// its emptiness, byte-length, or NUL-byte contract.
    pub fn named_optional(label: Option<&str>, objective: &str) -> Result<Self, StorageError> {
        if let Some(label) = label {
            validate_label(label)?;
        }
        validate_objective(objective)?;
        Ok(Self {
            kind: McpSessionKind::Named,
            label: label.map(str::to_owned),
            objective: objective.to_owned(),
        })
    }
}

